import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url);
const read=p=>readFileSync(new URL(p,root),'utf8');
const html=read('privacy.html');
const noticeSrc=read('parent-notice.js');
const settings=read('site-contact.js');
assert.match(html,/<strong>Netlify:<\/strong> currently hosts the website/);
assert.doesNotMatch(html,/<strong>GitHub Pages:<\/strong>/);
assert.match(html,/child-facing pages/);
assert.match(html,/Supabase database API/);
assert.match(html,/IP address/i);
assert.match(html,/CDN traffic and access logs are retained online for 30 days and in archives for up to 13 months/);
assert.match(html,/general platform logs for 90 days online and one year offline/);
assert.match(html,/security\/abuse logs for 365 days online and up to six years archived/);
assert.match(html,/does not establish which visitor identifiers are included in each archive/);
assert.match(html,/customer data is generally deleted within 90 days after service termination/);
assert.match(html,/26 subprocessors/);
assert.match(html,/The provider list alone does not show what information individual subprocessors actually receive/);
assert.match(html,/disabled by Resend default, but the operator must verify/);
assert.match(html,/Support email forwarding and Gmail/);
assert.match(html,/Delete account and family data/);
assert.match(html,/Withdraw/i);
assert.match(html,/parent-permission enrollment remains disabled/);
assert.match(noticeSrc,/"version": 5/);
assert.match(noticeSrc,/Netlify hosts the website/);
assert.match(settings,/privacyNoticeReviewed: false/);
assert.match(settings,/parentPermissionEnabled: false/);
const {parentNotice}=await import('data:text/javascript;base64,'+Buffer.from(noticeSrc).toString('base64'));
const {siteContact}=await import('data:text/javascript;base64,'+Buffer.from(settings).toString('base64'));
const contact={operatorName:siteContact.operatorName,mailingAddress:siteContact.mailingAddress,phone:siteContact.phone,supportEmail:siteContact.supportEmail};
const hash=createHash('sha256').update(JSON.stringify({notice:parentNotice,contact})).digest('hex');
assert.ok(read('supabase/migrations/20261121233000_parent_notice_v5_netlify_host.sql').includes(hash),'Notice and migration fingerprints differ');
for(const file of ['parent-permission-email','parent-permission-confirmation','parent-permission-rehearsal']){
 const edge=read('supabase/functions/'+file+'/index.ts');
 assert.match(edge,/"version": 5/,'Edge notice version must match '+file);
 assert.match(edge,/Netlify hosts the website/,'Edge host disclosure must match '+file);
}
console.log('PASS staged v5 privacy notice: host, log retention, requests, provider roles, parent rights, consent release flags and notice parity');
